// Tests: built-in agents load, tool catalog lists/adds safely (temp home, real start of each tool once).
import fs from "fs"; import os from "os"; import path from "path";
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "eta-cat-"));
process.env.USERPROFILE = tmp; process.env.HOME = tmp;
const { loadAgents } = await import("./agent.mjs");
const { listCatalog, addCatalogTool, TOOL_CATALOG } = await import("./catalog.mjs");
let pass = 0, fail = 0; const ok = (c, n) => { if (c) { pass++; console.log("  PASS  " + n); } else { fail++; console.log("  FAIL  " + n); } };
const ag = await loadAgents(null);
ok(ag.length >= 16 && ag.every((a) => a.scope === "bundled" && a.description && a.body.length > 300 && a.body.length < 3900), "16 built-in agents load, each with a description and a body under the 4000 character limit");
for (const n of ["code-reviewer", "debugger", "test-writer", "security-auditor", "hardener", "release-checker"]) ok(ag.some((a) => a.name === n), "agent " + n + " exists");
fs.mkdirSync(path.join(tmp, ".eta", "agents"), { recursive: true });
fs.writeFileSync(path.join(tmp, ".eta", "agents", "debugger.md"), "---\nname: debugger\ndescription: mine\n---\n\nMy own debugger rules. ".repeat(20));
const ag2 = await loadAgents(null);
ok(ag2.find((a) => a.name === "debugger").scope === "global", "a user's agent with the same name replaces the built-in one");
let l = await listCatalog(null);
ok(l.length === TOOL_CATALOG.length && l.every((t) => t.added === null), "catalog lists " + l.length + " tools, none added");
const r = await addCatalogTool({ id: "docs-context7", scope: "global", test: true });
ok(r.ok && !r.already, "adding a web tool works (it was started once to check)");
l = await listCatalog(null);
ok(l.find((t) => t.id === "docs-context7").added === "global", "the tool now shows as added");
const cfg = JSON.parse(fs.readFileSync(path.join(tmp, ".eta", "mcp.json"), "utf8"));
ok(cfg.mcpServers.context7.url === "https://mcp.context7.com/mcp", "saved in the all-projects tools file");
ok((await addCatalogTool({ id: "docs-context7", scope: "global" })).already === true, "adding it again does not change anything");
let e1 = ""; try { await addCatalogTool({ id: "nope" }); } catch (e) { e1 = e.message; } ok(/do not know/.test(e1), "unknown tool gives a clear error");
let e2 = ""; try { await addCatalogTool({ id: "memory", scope: "project" }); } catch (e) { e2 = e.message; } ok(/Open a project folder/.test(e2), "project scope without a folder gives a clear error");
const r3 = await addCatalogTool({ id: "thinking", scope: "global", test: true });
ok(r3.ok, "adding a local tool (npx) works (started once to check)");
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`\n========== ${pass} passed, ${fail} failed ==========`); process.exit(fail ? 1 : 0);
