// Eta pictures for the installer windows (instead of Inno Setup's own): big one on the welcome page, small one top right.
// 3 sizes each (100%, 150%, 200% screens). Inno wants BMP; sharp cannot write BMP, so a tiny 24-bit BMP writer.
const { createRequire } = await import("module");
const sharp = createRequire(path.join(ROOT, "console", "package.json"))("sharp");
const logoSvg = fs.readFileSync(path.join(ROOT, "brand", "eta-logo-white.svg"));
async function bmp(w, h, logoPart, file) {
  const s = Math.round(Math.min(w, h) * logoPart);
  const logo = await sharp(logoSvg, { density: 600 }).resize(s, s).png().toBuffer();
  const { data, info } = await sharp({ create: { width: w, height: h, channels: 3, background: "#000000" } })
    .composite([{ input: logo, left: Math.round((w - s) / 2), top: Math.round((h - s) / 2) }]).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const ch = info.channels; // 3 after removeAlpha (the logo layer had added a 4th, which broke the first picture)
  const row = Math.ceil((w * 3) / 4) * 4, img = Buffer.alloc(row * h);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) { const i = (y * w + x) * ch, o = (h - 1 - y) * row + x * 3; img[o] = data[i + 2]; img[o + 1] = data[i + 1]; img[o + 2] = data[i]; }
  const head = Buffer.alloc(54); head.write("BM", 0); head.writeUInt32LE(54 + img.length, 2); head.writeUInt32LE(54, 10); head.writeUInt32LE(40, 14);
  head.writeInt32LE(w, 18); head.writeInt32LE(h, 22); head.writeUInt16LE(1, 26); head.writeUInt16LE(24, 28); head.writeUInt32LE(img.length, 34);
  fs.writeFileSync(file, Buffer.concat([head, img])); return file;
}
const IMG = path.join(ROOT, "installer", "img"); fs.mkdirSync(IMG, { recursive: true });
const big = [], small = [];
for (const k of [1, 1.5, 2]) {
  big.push(await bmp(Math.round(164 * k), Math.round(314 * k), 0.62, path.join(IMG, `big-${k * 100}.bmp`)));
  small.push(await bmp(Math.round(55 * k), Math.round(55 * k), 0.7, path.join(IMG, `small-${k * 100}.bmp`)));
}

